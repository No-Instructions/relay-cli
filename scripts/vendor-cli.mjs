import { build } from "esbuild";
import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const upstream = process.argv[2];
if (!upstream || process.argv.length !== 3) throw new Error("Usage: node scripts/vendor-cli.mjs <Relay-checkout>");
const source = path.resolve(upstream);
const target = fileURLToPath(new URL("../vendor/relay-cli/", import.meta.url));
const result = await build({
  absWorkingDir: source,
  stdin: { contents: 'export { SERVER_TREE } from "./src/cli/server";', resolveDir: source },
  bundle: true, platform: "neutral", format: "esm", minify: true,
  write: false, metafile: true, target: "es2022",
  banner: { js: "// Generated by scripts/vendor-cli.mjs from Relay. MIT; see LICENSE and SOURCE.json." },
});
const files = {};
for (const input of Object.keys(result.metafile.inputs).filter(input => input !== "<stdin>").sort()) {
  if (!input.startsWith("src/cli/")) throw new Error(`Portable command graph imported ${input}`);
  files[input] = createHash("sha256").update(await fs.readFile(path.join(source, input))).digest("hex");
}
await fs.mkdir(target, { recursive: true });
await fs.writeFile(path.join(target, "server.js"), result.outputFiles[0].contents);
await fs.copyFile(path.join(source, "LICENSE"), path.join(target, "LICENSE"));
await fs.writeFile(path.join(target, "SOURCE.json"), JSON.stringify({
  repository: "https://github.com/No-Instructions/Relay", entry: "src/cli/server.ts", files,
  bundleSha256: createHash("sha256").update(result.outputFiles[0].contents).digest("hex"),
}, null, 2) + "\n");
console.log(`Vendored portable server commands: ${result.outputFiles[0].contents.length} bytes`);
